#!/usr/bin/env python3
"""Generate compact Pro exchange-rate screen fonts.

Run from GeekClock: .venv/bin/python firmware/tools/generate_exchange_assets.py
Uses the clock font pipeline; only exchange_assets.h is written.
"""
from pathlib import Path
from generate_assets import generate_4bit_font, format_c_bytes

FIRMWARE = Path(__file__).resolve().parents[1]
LABELS = (
    '일본 엔화 환율 기준 확인 갱신 중 저장값 최신 요청 대기 연결 오류 '
    '데이터 없음 출처 참고환율 은행 적용 다를 수 있음 다음 터치 새로고침 더블 다음 꾹 시계 원'
)
CHARSET = ''.join(chr(cp) for cp in range(0x20, 0x7f)) + LABELS + '¥₩·—'


def emit(out, name, size, charset):
    line_height, glyphs, bitmap = generate_4bit_font(charset, size, weight='bold', rounded=size >= 21)
    assert len(bitmap) <= 65535
    assert set(map(ord, charset)).issubset({g[0] for g in glyphs})
    out.extend([f'const uint8_t {name}_BITMAP[{len(bitmap)}] PROGMEM = {{', format_c_bytes(bitmap), '};',
                f'const Glyph4Bit {name}_GLYPHS[{len(glyphs)}] PROGMEM = {{'])
    out.extend('    { ' + ', '.join(map(str, glyph)) + ' },' for glyph in glyphs)
    out.extend(['};',f'const Font4Bit {name} PROGMEM = {{ {line_height}, {len(glyphs)}, {name}_GLYPHS, {name}_BITMAP }};', ''])
    return len(bitmap)


def main():
    out = ['#pragma once', '', '// Generated by firmware/tools/generate_exchange_assets.py.',
           '// Include after chiikawa_assets.h; reuses Font4Bit/Glyph4Bit definitions.', '']
    total = emit(out, 'FONT_FX_10', 10, CHARSET)
    total += emit(out, 'FONT_FX_13', 13, CHARSET)
    total += emit(out, 'FONT_FX_21', 21, '0123456789,. —')
    total += emit(out, 'FONT_FX_32', 32, '0123456789,. —')
    destination = FIRMWARE / 'src' / 'exchange_assets.h'
    destination.write_text('\n'.join(out).rstrip()+'\n', encoding='utf-8')
    print(f'Generated {destination}: {total:,} bitmap bytes')


if __name__ == '__main__':
    main()
