#!/usr/bin/env python3
"""Generate Pro pet fonts/expressions using the clock's existing art and palette.

Run from GeekClock: .venv/bin/python firmware/tools/generate_pet_assets.py
Only pet_assets.h is written; shared clock assets are read without modification.
"""
from __future__ import annotations

import argparse
from functools import lru_cache
from pathlib import Path
import re

from PIL import Image, ImageDraw

from generate_assets import (
    encode_rle6,
    format_c_bytes,
    generate_4bit_font,
    render_character_frames_rgba,
)


FIRMWARE = Path(__file__).resolve().parents[1]
KOREAN_LABELS = (
    "치이카와 다마고치 배부름 행복 기력 터치 놀이 꾹 밥 더블 시계 "
    "오늘도 함께 산책 중 맛있다 냠냠 좋아요 쿨쿨 쉬는 중 배고파요 놀아줘요 졸려요 레벨 환율"
)
CHARSET = "".join(chr(cp) for cp in range(0x20, 0x7F)) + KOREAN_LABELS + "♡♥★·"


def read_shared_palette() -> list[tuple[int, int, int]]:
    text = (FIRMWARE / "src" / "chiikawa_assets.h").read_text(encoding="utf-8")
    match = re.search(r"SPRITE_PALETTE_565\[49\].*?=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise ValueError("Shared RGB565 palette missing")
    values = [int(value, 16) for value in re.findall(r"0x[0-9A-Fa-f]+", match.group(1))]
    if len(values) != 49:
        raise ValueError("Shared palette must contain exactly 49 entries")
    return [
        (((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31)
        for v in values
    ]


def verify_rle(data: bytes, expected_pixels: int) -> None:
    cursor = 0
    pixels = 0
    while cursor < len(data):
        code = data[cursor]
        cursor += 1
        run = (code >> 6) + 1
        if code >> 6 == 3:
            if cursor >= len(data):
                raise ValueError("Truncated extended RLE run")
            run = data[cursor] + 4
            cursor += 1
        pixels += run
    if pixels != expected_pixels:
        raise ValueError(f"RLE decoded {pixels} pixels, expected {expected_pixels}")


def make_encoder(palette: list[tuple[int, int, int]]):
    @lru_cache(maxsize=None)
    def nearest(r: int, g: int, b: int) -> int:
        return min(
            range(1, 49),
            key=lambda idx: sum((a - z) ** 2 for a, z in zip(palette[idx], (r, g, b))),
        )

    def encode(im: Image.Image) -> bytes:
        indices: list[int] = []
        pixels = im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()
        for r, g, b, alpha in pixels:
            if alpha < 18:
                indices.append(0)
            elif alpha >= 228:
                indices.append(nearest(r, g, b))
            elif r < 140 and g < 130 and b < 135:
                indices.append(49 + min(14, max(0, (alpha - 16) * 15 // 224)))
            elif alpha >= 115:
                indices.append(nearest(r, g, b))
            else:
                indices.append(49 + min(14, max(0, alpha * 8 // 255)))
        data = encode_rle6(indices)
        verify_rle(data, im.width * im.height)
        if len(data) > 65535:
            raise ValueError("Sprite length exceeds SpriteFrameRLE uint16_t")
        return data

    return encode


def emit_font(out: list[str], name: str, size: int) -> int:
    line_height, glyphs, bitmap = generate_4bit_font(
        CHARSET, font_size=size, weight="bold" if size == 13 else "semibold", rounded=False
    )
    if len(bitmap) > 65535:
        raise ValueError(f"{name} bitmap offsets exceed uint16_t")
    if not set(map(ord, CHARSET)).issubset({entry[0] for entry in glyphs}):
        raise ValueError(f"{name} is missing a required glyph")
    for _, width, height, _, _, _, offset in glyphs:
        if offset + (width * height + 1) // 2 > len(bitmap):
            raise ValueError(f"{name} glyph bitmap exceeds bounds")
    out.extend([
        f"const uint8_t {name}_BITMAP[{len(bitmap)}] PROGMEM = {{",
        format_c_bytes(bitmap),
        "};",
        f"const Glyph4Bit {name}_GLYPHS[{len(glyphs)}] PROGMEM = {{",
    ])
    out.extend(f"    {{ {', '.join(map(str, glyph))} }}," for glyph in glyphs)
    out.extend([
        "};",
        f"const Font4Bit {name} PROGMEM = {{ {line_height}, {len(glyphs)}, {name}_GLYPHS, {name}_BITMAP }};",
        "",
    ])
    return len(bitmap)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview-dir", type=Path)
    args = parser.parse_args()

    encode = make_encoder(read_shared_palette())
    out = [
        "#pragma once",
        "",
        "// Generated by firmware/tools/generate_pet_assets.py. Do not edit by hand.",
        "// Regenerate: .venv/bin/python firmware/tools/generate_pet_assets.py",
        "// Include after chiikawa_assets.h; reuses its structs and RGB565 palette.",
        "",
    ]
    sprite_bytes = 0
    preview_frames: list[tuple[str, Image.Image]] = []
    for name, mood in [("SLEEP", "sleep"), ("EAT", "eat"), ("SAD", "cry")]:
        width, height, frames = render_character_frames_rgba("chiikawa", mood=mood)
        assert (width, height) == (116, 108)
        encoded = [encode(frame) for frame in frames]
        for i, data in enumerate(encoded):
            out.extend([
                f"const uint8_t SPR_PET_{name}_F{i}[{len(data)}] PROGMEM = {{",
                format_c_bytes(data),
                "};",
            ])
        out.append(f"const SpriteFrameRLE CHAR_FRAMES_PET_{name}[4] PROGMEM = {{")
        out.extend(f"    {{ {len(data)}, SPR_PET_{name}_F{i} }}," for i, data in enumerate(encoded))
        out.extend(["};", ""])
        sprite_bytes += sum(map(len, encoded))
        preview_frames.append((name, frames[0]))

    out.extend(["constexpr uint16_t CHAR_PET_W = 116;", "constexpr uint16_t CHAR_PET_H = 108;", ""])
    font_bytes = emit_font(out, "FONT_PET_10", 10) + emit_font(out, "FONT_PET_13", 13)
    destination = FIRMWARE / "src" / "pet_assets.h"
    destination.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")

    if args.preview_dir:
        args.preview_dir.mkdir(parents=True, exist_ok=True)
        collage = Image.new("RGB", (116 * 3, 132), (255, 238, 244))
        draw = ImageDraw.Draw(collage)
        for idx, (name, frame) in enumerate(preview_frames):
            collage.paste(frame, (idx * 116, 0), frame)
            draw.text((idx * 116 + 40, 114), name, fill=(70, 45, 55))
            frame.save(args.preview_dir / f"pet-{name.lower()}.png")
        collage.resize((696, 264), Image.Resampling.NEAREST).save(args.preview_dir / "pet-expressions.png")

    print(f"Generated {destination}")
    print(f"12 mood frames verified: 116x108; compressed sprite bytes={sprite_bytes:,}")
    print(f"Font bitmap bytes={font_bytes:,}; total bitmap/RLE payload={sprite_bytes + font_bytes:,}")


if __name__ == "__main__":
    main()
