#!/usr/bin/env python3
"""Generate compact Korean labels for the Pro study timer and room UI.

Run from GeekClock: .venv/bin/python firmware/tools/generate_study_assets.py
"""
from pathlib import Path
from generate_assets import generate_4bit_font, format_c_bytes

ROOT = Path(__file__).resolve().parents[1]
LABELS = (
    "치이카와 뽀모도로 집중 짧은 휴식 긴 휴식 준비 일시정지 진행 중 완료 시작 코인 보상 회 달성 "
    "집중하면 방이 예뻐져요 터치 정지 꾹 초기화 더블 다음 화면 모아 집 꾸미기 치이카와의 방 "
    "다시 충전 공부 총 분 수고했어요 쉬어가요 다음 소다 벽지 별밤 딸기 러그 구름 침대 달빛 초록 화분 별빛 스탠드 "
)
CHARSET = ''.join(chr(i) for i in range(32, 127)) + LABELS + '·♡♥★'


def main():
    out = ['#pragma once', '// Generated by tools/generate_study_assets.py; include after chiikawa_assets.h.', '']
    total = 0
    for size in [10, 13]:
        line, glyphs, bitmap = generate_4bit_font(CHARSET, size, weight='bold')
        assert len(bitmap) < 65536
        name = f'FONT_STUDY_{size}'
        out += [f'const uint8_t {name}_BITMAP[{len(bitmap)}] PROGMEM = {{', format_c_bytes(bitmap), '};',
                f'const Glyph4Bit {name}_GLYPHS[{len(glyphs)}] PROGMEM = {{']
        out += [f'    {{ {cp}, {w}, {h}, {x}, {y}, {advance}, {offset} }},'
                for cp, w, h, x, y, advance, offset in glyphs]
        out += ['};', f'const Font4Bit {name} PROGMEM = {{ {line}, {len(glyphs)}, {name}_GLYPHS, {name}_BITMAP }};', '']
        total += len(bitmap)
    destination = ROOT / 'src/study_assets.h'
    destination.write_text('\n'.join(out).rstrip() + '\n')
    print(f'Generated {destination}: {total:,} bitmap bytes, {len(glyphs)} glyphs per font')

if __name__ == '__main__':
    main()
